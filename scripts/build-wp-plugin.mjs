// Packages the WordPress plugin: builds the library, generates the PHP module
// whitelist from catalog.js, syncs compiled assets into the plugin, zips it.
import { execSync } from 'node:child_process';
import { cpSync, rmSync, writeFileSync, mkdirSync } from 'node:fs';

const PLUGIN = 'wp-plugin/living-assets-wp';

execSync('node build.mjs', { stdio: 'inherit' });

const { CATALOG } = await import('../assets/core/catalog.js');

// ---- includes/catalog.php: server-side whitelist + labels -----------------
const php = (s) => String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
const entries = CATALOG.map((m) =>
  `\t'${m.id}' => [ 'label' => '${php(m.name)}', 'subtitle' => '${php(m.subtitle)}', 'renderer' => '${m.renderer}' ],`,
).join('\n');

writeFileSync(`${PLUGIN}/includes/catalog.php`, `<?php
/**
 * GENERATED by scripts/build-wp-plugin.mjs from src/core/catalog.ts — do not edit.
 * Module whitelist: only these ids may be mounted.
 */

if ( ! defined( 'ABSPATH' ) ) { exit; }

function lawp_catalog(): array {
\treturn [
${entries}
\t];
}

function lawp_module_exists( string $id ): bool {
\treturn array_key_exists( $id, lawp_catalog() );
}

function lawp_module_label( string $id ): string {
\treturn lawp_catalog()[ $id ]['label'] ?? $id;
}
`);

// ---- sync compiled library into the plugin --------------------------------
const LA = `${PLUGIN}/public/assets/la`;
rmSync(LA, { recursive: true, force: true });
mkdirSync(`${LA}`, { recursive: true });
cpSync('assets', `${LA}`, { recursive: true });        // compiled modules (incl. core/player)
cpSync('vendor', `${LA}/vendor`, { recursive: true }); // three, mp4-muxer
console.log('library synced into plugin');

// ---- zip ------------------------------------------------------------------
execSync(`cd wp-plugin && rm -f living-assets-wp.zip && zip -qr living-assets-wp.zip living-assets-wp`, { stdio: 'inherit' });
execSync('ls -la wp-plugin/living-assets-wp.zip', { stdio: 'inherit' });
console.log('plugin packaged: wp-plugin/living-assets-wp.zip');
